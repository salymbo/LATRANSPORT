-- 1. Tables -------------------------------------------------

create table if not exists public.camions (
  id text primary key,
  modele text not null,
  annee int,
  km int default 0,
  etat text not null default 'En service',
  created_at timestamptz not null default now()
);

create table if not exists public.chauffeurs (
  id bigint generated by default as identity primary key,
  nom text not null,
  permis text,
  tel text,
  camion text references public.camions (id) on delete set null,
  statut text not null default 'Disponible',
  created_at timestamptz not null default now(),
  constraint chauffeurs_unique unique (nom, tel)
);

create table if not exists public.voyages (
  id bigint generated by default as identity primary key,
  date date not null default current_date,
  camion text references public.camions (id) on delete set null,
  chauffeur text,
  materiaux text,
  trajet text,
  tonnes numeric(8, 2) not null default 0 check (tonnes >= 0),
  created_at timestamptz not null default now(),
  constraint voyages_unique unique (date, camion, chauffeur, materiaux, trajet, tonnes)
);

create index if not exists voyages_date_idx on public.voyages (date desc);

-- 2. Sécurité : lecture réservée aux utilisateurs connectés --

alter table public.camions enable row level security;
alter table public.chauffeurs enable row level security;
alter table public.voyages enable row level security;

drop policy if exists "lecture camions" on public.camions;
drop policy if exists "lecture chauffeurs" on public.chauffeurs;
drop policy if exists "lecture voyages" on public.voyages;

create policy "lecture camions" on public.camions
  for select to authenticated using (true);

create policy "lecture chauffeurs" on public.chauffeurs
  for select to authenticated using (true);

create policy "lecture voyages" on public.voyages
  for select to authenticated using (true);

